"""Generate <kythira/kms/kms_actions.hpp> from AWS's service reference.

The input is the `kms` entry of AWS's machine-readable Service
Authorization Reference
(https://servicereference.us-east-1.amazonaws.com/v1/kms/kms.json),
pinned as tools/kms-service-reference.json. The output holds:

- kms_actions(): every action with the ARN formats of the resources it
  acts on (`key`, `alias`) and its condition keys (action keys plus the
  resources', and the Kythira extension keys listed below), for the IAM
  authorizer's service registry (.kiro/specs/kms-compatible-api/
  Requirement 7.4);
- k_operation_actions: per API operation, every `kms` action AWS checks
  for it, and whether any of them writes. ReEncrypt is the one operation
  with two (ReEncryptFrom on the source key, ReEncryptTo on the
  destination); CreateAlias and UpdateAlias act on an alias and a key;
- kms_static_roles(): the static-key roles of Requirement 7.7. read-only
  is every action the reference marks neither write nor permissions
  management (describe, get, list); read-write adds the cryptographic
  operations, listed below because the reference marks them all as
  writes, the same as key management; admin is everything.

Usage:
    gen_kms_actions.py REFERENCE OUT [--check]
"""

import argparse
import json
import pathlib
import sys

HEADER = """\
// Copyright (c) 2026 Clark Rawlins
// SPDX-License-Identifier: Apache-2.0

// GENERATED by services/kms/tools/gen_kms_actions.py from
// services/kms/tools/kms-service-reference.json (AWS Service
// Authorization Reference, {version}). Do not edit; regenerate.

#pragma once

/// @file kms_actions.hpp
/// @brief The `kms` action table, the operation-to-action map and the
///        static-key roles (`.kiro/specs/kms-compatible-api/`
///        Requirement 7.4, 7.7).

#include <raft/aws_request_authorizer.hpp>
#include <raft/static_key_authorizer.hpp>

#include <algorithm>
#include <array>
#include <string_view>

namespace kythira::kms {{

// clang-format off
"""

FOOTER = """\
// clang-format on

/// The entry for an API operation, or nullptr when the reference has none.
[[nodiscard]] constexpr auto find_operation_actions(std::string_view operation)
    -> const operation_actions* {
    const auto* it = std::lower_bound(
        k_operation_actions.begin(), k_operation_actions.end(), operation,
        [](const operation_actions& e, std::string_view name) { return e.operation < name; });
    return it != k_operation_actions.end() && it->operation == operation ? it : nullptr;
}

}  // namespace kythira::kms
"""


# The cryptographic operations (AWS KMS Developer Guide, "Cryptographic
# operations"), the read-write role's additions.
CRYPTOGRAPHIC = {
    "Decapsulate",
    "Decrypt",
    "DeriveSharedSecret",
    "Encapsulate",
    "Encrypt",
    "GenerateDataKey",
    "GenerateDataKeyPair",
    "GenerateDataKeyPairWithoutPlaintext",
    "GenerateDataKeyWithoutPlaintext",
    "GenerateMac",
    "GenerateRandom",
    "ReEncryptFrom",
    "ReEncryptTo",
    "Sign",
    "Verify",
    "VerifyMac",
}


# Condition keys Kythira adds to AWS's actions. Decrypt's Kythira
# recipient (KYTHIRA_HPKE_X25519_SHA256_AES256GCM, the EC2 controller's
# VolumeKey) names the X25519 key it seals to, so a key policy can allow
# only enrolled helm transport keys (.kiro/specs/ec2-compatible-api/
# Requirement 10.3).
KYTHIRA_CONDITION_KEYS = {
    "Decrypt": ["kms:KythiraRecipientPublicKeySha256"],
}


def q(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def props(action):
    return action.get("Annotations", {}).get("Properties", {})


def generate(ref):
    resources = {r["Name"]: r for r in ref["Resources"]}
    actions = {a["Name"]: a for a in ref["Actions"]}
    out = [HEADER.format(version=ref.get("Version", "unversioned"))]

    out.append("/// Every `kms` action, its resource ARN formats and condition keys.")
    out.append("[[nodiscard]] inline auto kms_actions() -> aws_auth::aws_action_table {")
    out.append("    return {")
    out.append('        .service_prefix = "kms",')
    out.append("        .actions = {")
    for name in sorted(actions):
        a = actions[name]
        arns, keys = [], list(a.get("ActionConditionKeys", []))
        for r in a.get("Resources", []):
            res = resources[r["Name"]]
            arns += res["ARNFormats"]
            keys += res.get("ConditionKeys", [])
            keys += r.get("ConditionKeys", [])
        if not arns:
            arns = ["*"]
        keys += KYTHIRA_CONDITION_KEYS.get(name, [])
        keys = sorted(set(keys))
        out.append(
            "            {%s, {%s}, {%s}},"
            % (q(name), ", ".join(map(q, arns)), ", ".join(map(q, keys)))
        )
    out.append("        },")
    out.append("    };")
    out.append("}")
    out.append("")

    ops = sorted(ref["Operations"], key=lambda o: o["Name"])
    rows = []
    for o in ops:
        acts = sorted(
            a["Name"]
            for a in o.get("AuthorizedActions", [])
            if a.get("Service", "kms") == "kms"
        )
        writes = any(props(actions[a]).get("IsWrite", False) for a in acts if a in actions)
        rows.append((o["Name"], acts, writes))
    width = max(len(r[1]) for r in rows)
    out.append("/// Every `kms` action AWS may check for an API operation (a superset;")
    out.append("/// (see the generator's docstring), and whether any of them writes.")
    out.append("struct operation_actions {")
    out.append("    std::string_view operation;")
    out.append("    std::array<std::string_view, %d> actions;  // unused slots empty" % width)
    out.append("    bool writes = false;")
    out.append("};")
    out.append("")
    out.append("/// Sorted by operation name.")
    out.append(
        "inline constexpr std::array<operation_actions, %d> k_operation_actions{{" % len(rows)
    )
    for name, acts, writes in rows:
        out.append(
            "    {%s, {%s}, %s}," % (q(name), ", ".join(map(q, acts)), "true" if writes else "false")
        )
    out.append("}};")
    out.append("")

    missing = CRYPTOGRAPHIC - set(actions)
    if missing:
        raise SystemExit("cryptographic actions not in the reference: %s" % sorted(missing))
    ro, rw = [], []
    for name in sorted(actions):
        p = props(actions[name])
        write, perm = (p.get(k, False) for k in ("IsWrite", "IsPermissionManagement"))
        if not write and not perm:
            ro.append(name)
        elif name in CRYPTOGRAPHIC:
            rw.append(name)
    out.append("/// The static-key roles: read-only describes and lists, read-write adds")
    out.append("/// the cryptographic operations, admin is everything")
    out.append("/// (`static_key_authorizer`).")
    out.append("[[nodiscard]] inline auto kms_static_roles() -> aws_auth::static_role_table {")
    out.append("    return {")
    out.append('        "kms",')
    out.append("        {%s}," % ", ".join(map(q, ro)))
    out.append("        {%s}," % ", ".join(map(q, rw)))
    out.append("    };")
    out.append("}")
    out.append("")
    out.append(FOOTER)
    return "\n".join(out)


def main(argv):
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("reference")
    ap.add_argument("out")
    ap.add_argument("--check", action="store_true", help="fail if OUT is stale")
    args = ap.parse_args(argv)
    text = generate(json.loads(pathlib.Path(args.reference).read_text(encoding="utf-8")))
    out = pathlib.Path(args.out)
    if args.check:
        if not out.exists() or out.read_text(encoding="utf-8") != text:
            print("%s is stale; run %s" % (out, sys.argv[0]), file=sys.stderr)
            return 1
        return 0
    out.write_text(text, encoding="utf-8")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
