"""Generate <kythira/sqs/sqs_actions.hpp> from AWS's service reference.

The input is the `sqs` entry of AWS's machine-readable Service
Authorization Reference
(https://servicereference.us-east-1.amazonaws.com/v1/sqs/sqs.json),
pinned as tools/sqs-service-reference.json. The output holds:

- sqs_actions(): every action with the ARN formats of the resources it
  acts on and its condition keys (action keys plus the resources'), for the
  IAM authorizer's service registry;
- k_operation_actions: per API operation, every `sqs` action AWS may
  check for it, and whether the operation writes. The action list is a
  superset: CreateQueue lists TagQueue, needed only when the request has
  tags, and the batch operations list their single-entry actions (SQS has
  no SendMessageBatch action). The front end authorizes the operation's
  primary action (`primary_action`) and adds TagQueue itself when tags are
  present. "Writes" means the operation must go through the leader:
  ReceiveMessage is a read to IAM but changes visibility and receive
  counts, so it is a committed entry (design: "A receive is a write") and
  is forced to writing here;
- sqs_static_roles(): the static-key roles. SQS's reference has no
  `IsDataPlane` property, so the message actions are named here
  (`MESSAGE_ACTIONS`). Read-only is every action that neither writes nor
  manages permissions, less ReceiveMessage, which consumes (AWS's
  AmazonSQSReadOnlyAccess policy leaves it out too); read-write adds the
  message actions; admin is everything.

Usage:
    gen_sqs_actions.py REFERENCE OUT [--check]
"""

import argparse
import json
import pathlib
import sys

# The message actions: what a read-write static key adds to read-only.
MESSAGE_ACTIONS = ("ChangeMessageVisibility", "DeleteMessage", "ReceiveMessage", "SendMessage")

# Operations that change queue state although every action they need is a
# read to IAM.
FORCED_WRITES = ("ReceiveMessage",)

# The action that authorizes each batch operation.
BATCH_PRIMARY = {
    "ChangeMessageVisibilityBatch": "ChangeMessageVisibility",
    "DeleteMessageBatch": "DeleteMessage",
    "SendMessageBatch": "SendMessage",
}

HEADER = """\
// Copyright (c) 2026 Clark Rawlins
// SPDX-License-Identifier: Apache-2.0

// GENERATED by services/sqs/tools/gen_sqs_actions.py from
// services/sqs/tools/sqs-service-reference.json (AWS Service
// Authorization Reference, {version}). Do not edit; regenerate.

#pragma once

/// @file sqs_actions.hpp
/// @brief The `sqs` action table, the operation-to-action map and the
///        static-key roles (`.kiro/specs/sqs-compatible-queues/`
///        Requirement 3.3).

#include <raft/aws_request_authorizer.hpp>
#include <raft/static_key_authorizer.hpp>

#include <algorithm>
#include <array>
#include <string_view>

namespace kythira::sqs {{

// clang-format off
"""

FOOTER = """\
// clang-format on

/// The entry for an API operation, or nullptr when the reference has none.
[[nodiscard]] constexpr auto find_operation_actions(std::string_view operation)
    -> const operation_actions* {
    const auto* it = std::lower_bound(
        k_operation_actions.begin(), k_operation_actions.end(), operation,
        [](const operation_actions& e, std::string_view name) { return e.operation < name; });
    return it != k_operation_actions.end() && it->operation == operation ? it : nullptr;
}

}  // namespace kythira::sqs
"""


def q(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def props(action):
    return action.get("Annotations", {}).get("Properties", {})


def generate(ref):
    resources = {r["Name"]: r for r in ref["Resources"]}
    actions = {a["Name"]: a for a in ref["Actions"]}
    out = [HEADER.format(version=ref.get("Version", "unversioned"))]

    out.append("/// Every `sqs` action, its resource ARN formats and condition keys.")
    out.append("[[nodiscard]] inline auto sqs_actions() -> aws_auth::aws_action_table {")
    out.append("    return {")
    out.append('        .service_prefix = "sqs",')
    out.append("        .actions = {")
    for name in sorted(actions):
        a = actions[name]
        arns, keys = [], list(a.get("ActionConditionKeys", []))
        for r in a.get("Resources", []):
            res = resources[r["Name"]]
            arns += res["ARNFormats"]
            keys += res.get("ConditionKeys", [])
            keys += r.get("ConditionKeys", [])
        if not arns:
            arns = ["*"]
        keys = sorted(set(keys))
        out.append(
            "            {%s, {%s}, {%s}},"
            % (q(name), ", ".join(map(q, arns)), ", ".join(map(q, keys)))
        )
    out.append("        },")
    out.append("    };")
    out.append("}")
    out.append("")

    ops = sorted(ref["Operations"], key=lambda o: o["Name"])
    rows = []
    for o in ops:
        acts = sorted(
            a["Name"]
            for a in o.get("AuthorizedActions", [])
            if a.get("Service", "sqs") == "sqs"
        )
        writes = o["Name"] in FORCED_WRITES or any(
            props(actions[a]).get("IsWrite", False) for a in acts if a in actions
        )
        primary = BATCH_PRIMARY.get(o["Name"], o["Name"])
        if primary not in acts:
            raise SystemExit("%s: primary action %s not in its list" % (o["Name"], primary))
        rows.append((o["Name"], acts, writes, primary))
    width = max(len(r[1]) for r in rows)
    out.append("/// Every `sqs` action AWS may check for an API operation (a superset;")
    out.append("/// see the generator's docstring), the one action that authorizes it,")
    out.append("/// and whether it must go through the leader.")
    out.append("struct operation_actions {")
    out.append("    std::string_view operation;")
    out.append("    std::array<std::string_view, %d> actions;  // unused slots empty" % width)
    out.append("    std::string_view primary_action;")
    out.append("    bool writes = false;")
    out.append("};")
    out.append("")
    out.append("/// Sorted by operation name.")
    out.append(
        "inline constexpr std::array<operation_actions, %d> k_operation_actions{{" % len(rows)
    )
    for name, acts, writes, primary in rows:
        out.append(
            "    {%s, {%s}, %s, %s},"
            % (q(name), ", ".join(map(q, acts)), q(primary), "true" if writes else "false")
        )
    out.append("}};")
    out.append("")

    ro, rw = [], []
    for name in sorted(actions):
        p = props(actions[name])
        if name in MESSAGE_ACTIONS:
            rw.append(name)
        elif not p.get("IsWrite", False) and not p.get("IsPermissionManagement", False):
            ro.append(name)
    missing = sorted(set(MESSAGE_ACTIONS) - set(actions))
    if missing:
        raise SystemExit("message actions missing from the reference: %s" % ", ".join(missing))
    out.append("/// The static-key roles: read-only reads queue metadata, read-write adds")
    out.append("/// the message actions, admin is everything (`static_key_authorizer`).")
    out.append("[[nodiscard]] inline auto sqs_static_roles() -> aws_auth::static_role_table {")
    out.append("    return {")
    out.append('        "sqs",')
    out.append("        {%s}," % ", ".join(map(q, ro)))
    out.append("        {%s}," % ", ".join(map(q, rw)))
    out.append("    };")
    out.append("}")
    out.append("")
    out.append(FOOTER)
    return "\n".join(out)


def main(argv):
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("reference")
    ap.add_argument("out")
    ap.add_argument("--check", action="store_true", help="fail if OUT is stale")
    args = ap.parse_args(argv)
    text = generate(json.loads(pathlib.Path(args.reference).read_text(encoding="utf-8")))
    out = pathlib.Path(args.out)
    if args.check:
        if not out.exists() or out.read_text(encoding="utf-8") != text:
            print("%s is stale; run %s" % (out, sys.argv[0]), file=sys.stderr)
            return 1
        return 0
    out.write_text(text, encoding="utf-8")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
