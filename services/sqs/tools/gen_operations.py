"""Generate the SQS operation table from the pinned botocore model.

Reads services/sqs/model/service-2.json and writes
services/sqs/include/kythira/sqs/sqs_operations.hpp: one entry per
operation, sorted by name, with whether it is the batch form of another
operation and which of the model's error shapes it may return, plus the
model's error shapes themselves. The header is checked in so that a model
upgrade shows its effect in the pull request's diff
(.kiro/specs/sqs-compatible-queues/ Requirement 2.1).

    gen_operations.py MODEL HEADER          write HEADER
    gen_operations.py MODEL HEADER --check  exit 1 if HEADER is stale

The ctest sqs_operations_up_to_date runs the --check form.
"""

import argparse
import json
import pathlib
import sys

BOTOCORE_VERSION = "1.43.100"


def render(model: dict) -> str:
    meta = model["metadata"]
    shapes = model["shapes"]
    ops = sorted(model["operations"].items())
    errors = sorted(name for name, shape in shapes.items() if shape.get("exception"))
    index = {name: i for i, name in enumerate(errors)}
    for name, op in ops:
        for e in op.get("errors", []):
            if e["shape"] not in index:
                raise SystemExit(f"{name} lists error {e['shape']}, which is not an exception shape")
    names = {name for name, _ in ops}
    lines = [
        "// Generated by services/sqs/tools/gen_operations.py from",
        f"// services/sqs/model/service-2.json (botocore {BOTOCORE_VERSION}). Do not edit:",
        "// change the model or the generator and rerun it.",
        "#pragma once",
        "",
        "#include <array>",
        "#include <cstddef>",
        "#include <cstdint>",
        "#include <string_view>",
        "",
        "namespace kythira::sqs {",
        "",
        f'inline constexpr std::string_view botocore_version = "{BOTOCORE_VERSION}";',
        f'inline constexpr std::string_view api_version = "{meta["apiVersion"]}";',
        f'inline constexpr std::string_view json_version = "{meta["jsonVersion"]}";',
        "/// `X-Amz-Target` is this prefix, a dot and the operation name.",
        f'inline constexpr std::string_view target_prefix = "{meta["targetPrefix"]}";',
        "/// The model is marked `awsQueryCompatible`: JSON error responses also",
        "/// carry the query protocol's error code (`x-amzn-query-error`), and the",
        "/// query protocol is still accepted (Requirement 3.1).",
        f"inline constexpr bool aws_query_compatible = {'true' if 'awsQueryCompatible' in meta else 'false'};",
        "",
        "/// Every error shape in the model, sorted by name. An operation names",
        "/// the ones it may return by index into this array.",
        f"inline constexpr std::array<std::string_view, {len(errors)}> error_shapes{{{{",
    ]
    lines += [f'    "{e}",' for e in errors]
    lines += [
        "}};",
        "",
        "/// One operation of the pinned SQS model.",
        "struct operation_info {",
        "    std::string_view _name;",
        "    /// The batch form of another operation (`SendMessageBatch` of",
        "    /// `SendMessage`): up to ten entries, a result or error per entry.",
        "    bool _batch = false;",
        "    /// Bit i set: the operation may return `error_shapes[i]`.",
        "    std::uint64_t _errors = 0;",
        "",
        "    [[nodiscard]] constexpr auto may_return(std::size_t error_index) const -> bool {",
        "        return error_index < 64 && ((_errors >> error_index) & 1U) != 0;",
        "    }",
        "};",
        "",
        "/// Every operation in the model, sorted by name.",
        f"inline constexpr std::array<operation_info, {len(ops)}> operations{{{{",
    ]
    if len(errors) > 64:
        raise SystemExit(f"{len(errors)} error shapes do not fit a 64-bit mask")
    for name, op in ops:
        batch = name.endswith("Batch") and name[: -len("Batch")] in names
        mask = 0
        for e in op.get("errors", []):
            mask |= 1 << index[e["shape"]]
        lines.append(f'    {{"{name}", {"true" if batch else "false"}, 0x{mask:x}U}},')
    lines += ["}};", "", "}  // namespace kythira::sqs", ""]
    return "\n".join(lines)


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("model", type=pathlib.Path)
    ap.add_argument("header", type=pathlib.Path)
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    text = render(json.loads(args.model.read_text(encoding="utf-8")))
    if args.check:
        current = args.header.read_text(encoding="utf-8") if args.header.exists() else ""
        if current != text:
            print(f"{args.header} is stale: rerun {sys.argv[0]} {args.model} {args.header}",
                  file=sys.stderr)
            return 1
        return 0
    if not args.header.exists() or args.header.read_text(encoding="utf-8") != text:
        args.header.write_text(text, encoding="utf-8")
    return 0


if __name__ == "__main__":
    sys.exit(main())
