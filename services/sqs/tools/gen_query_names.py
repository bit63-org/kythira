"""Generate <kythira/sqs/model/sqs_query_names.hpp>: the AWS query protocol's
names for the SQS model.

SQS speaks two protocols over one set of shapes. The pinned JSON model
(model/service-2.json, botocore 1.43.100) has the shapes; the query names
(`Attribute.1.Name`, flattened `<Message>` lists, error codes such as
`AWS.SimpleQueueService.NonExistentQueue`) were dropped from it when SQS
moved to JSON. They come from the last query-era model, botocore 1.31.40's,
pinned as model/query/service-2.json. Both are botocore's, Apache-2.0
(model/LICENSE, model/NOTICE).

The output holds, for every structure member of the JSON model:

- `name`: the member's query name: the member's `locationName`, else its
  shape's, else the member name;
- `item`: for a list, the name of each element: a flattened list repeats
  `item` in place of the member (`AttributeName.1`, `<Message>`), a wrapped
  one nests it under `name` (`member` when the model names none);
- `key`, `value`: for a map, the entry's key and value names (`Name` and
  `Value`; botocore's defaults `key` and `value`);
- `flattened`: from the member or its shape.

These are botocore's QuerySerializer and QueryParser rules, applied once
here so the C++ codec only reads the table. A member the query model lacks
(ReceiveMessage's `MessageSystemAttributeNames`, added after the move to
JSON) gets the defaults, so it can be sent both ways.

It also holds every exception shape's query error: code, HTTP status and
fault side. The query model has them for most shapes; a shape it lacks, or
has without an `error` block, answers with its own name, status 400 and
fault Sender, which is how SQS names those errors in its API reference.
The exceptions added after the move to JSON (the `Kms*` family,
`InvalidAddress`, `InvalidSecurity`, `RequestThrottled`,
`InvalidAttributeValue`) are in that group; their codes are unverified until
recorded against real SQS (`.kiro/specs/sqs-compatible-queues/` task 13),
and the fix for any difference belongs in `QUERY_ERROR_OVERRIDES` below.

Usage:
    gen_query_names.py JSON_MODEL QUERY_MODEL OUT [--check]
"""

import argparse
import json
import pathlib
import sys

# Query errors that neither model gives, as (code, status, sender fault),
# each from task 13's recordings of real SQS
# (tests/differential/recordings/aws-seed-*.json).
QUERY_ERROR_OVERRIDES = {
    # ChangeMessageVisibility and DeleteMessage with "not-a-handle" answer
    # 404 (seed 1 step 75, seed 2 step 144); the botocore models give no
    # status, and the Smithy model's awsQueryError trait agrees on 404.
    "ReceiptHandleIsInvalid": ("ReceiptHandleIsInvalid", 404, True),
}

HEADER = """\
// Copyright (c) 2026 Clark Rawlins
// SPDX-License-Identifier: Apache-2.0

// GENERATED by services/sqs/tools/gen_query_names.py from
// services/sqs/model/service-2.json ({json_uid}) and
// services/sqs/model/query/service-2.json (the query-era model, {query_uid}).
// Do not edit; regenerate.

#pragma once

/// @file sqs_query_names.hpp
/// @brief The AWS query protocol's member names and error codes for the SQS
///        model (`.kiro/specs/sqs-compatible-queues/` Requirement 3.1).

#include <algorithm>
#include <array>
#include <string_view>
#include <utility>

namespace kythira::sqs::sqs_query {{

/// The query names of one structure member.
struct member_names {{
    std::string_view shape;   ///< the structure, by JSON-model name
    std::string_view member;  ///< the member, by JSON-model name
    std::string_view name;
    std::string_view item;
    std::string_view key;
    std::string_view value;
    bool flattened = false;
}};

/// One exception shape's query error.
struct query_error {{
    std::string_view shape;
    std::string_view code;
    unsigned status = 400;
    bool sender = true;
}};

inline constexpr std::string_view k_api_version = "{api_version}";
inline constexpr std::string_view k_xml_namespace = "{xml_namespace}";

// clang-format off
"""

FOOTER = """\
// clang-format on

/// The names of `shape`.`member`, or nullptr when the JSON model has no
/// such structure member.
[[nodiscard]] constexpr auto find_member(std::string_view shape, std::string_view member)
    -> const member_names* {
    const auto key = std::pair{shape, member};
    const auto* it = std::lower_bound(
        k_members.begin(), k_members.end(), key,
        [](const member_names& e, const std::pair<std::string_view, std::string_view>& k) {
            return std::pair{e.shape, e.member} < k;
        });
    return it != k_members.end() && it->shape == shape && it->member == member ? it : nullptr;
}

/// The query error of exception shape `shape`, or nullptr when it is not one.
[[nodiscard]] constexpr auto find_error(std::string_view shape) -> const query_error* {
    const auto* it =
        std::lower_bound(k_errors.begin(), k_errors.end(), shape,
                         [](const query_error& e, std::string_view s) { return e.shape < s; });
    return it != k_errors.end() && it->shape == shape ? it : nullptr;
}

}  // namespace kythira::sqs::sqs_query
"""


def q(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def merged(ref, shapes):
    """botocore's view of a member: its shape's traits under the member's."""
    out = {k: v for k, v in shapes.get(ref["shape"], {}).items() if k in ("locationName", "flattened")}
    out.update({k: v for k, v in ref.items() if k in ("locationName", "flattened")})
    return out


def names_of(struct_name, member_name, new_shapes, old_shapes):
    new_ref = new_shapes[struct_name]["members"][member_name]
    old_struct = old_shapes.get(struct_name, {})
    old_ref = old_struct.get("members", {}).get(member_name)
    # The query model's view where it has the member, the JSON model's
    # (which carries no query names) otherwise.
    shapes = old_shapes if old_ref is not None else new_shapes
    ref = old_ref if old_ref is not None else new_ref
    target = shapes.get(ref["shape"], new_shapes[new_ref["shape"]])
    traits = merged(ref, shapes)
    name = traits.get("locationName", member_name)
    flattened = bool(traits.get("flattened", False))
    item = key = value = ""
    kind = new_shapes[new_ref["shape"]]["type"]
    if kind == "list":
        item = target.get("member", {}).get("locationName", "" if flattened else "member")
        if flattened and not item:
            item = name
    elif kind == "map":
        key = target.get("key", {}).get("locationName", "key")
        value = target.get("value", {}).get("locationName", "value")
    return name, item, key, value, flattened


def generate(new, old):
    new_shapes, old_shapes = new["shapes"], old["shapes"]
    out = [
        HEADER.format(
            json_uid=new["metadata"]["uid"],
            query_uid=old["metadata"]["uid"],
            api_version=old["metadata"]["apiVersion"],
            xml_namespace=old["metadata"]["xmlNamespace"],
        )
    ]
    rows = []
    for sname in sorted(new_shapes):
        s = new_shapes[sname]
        if s["type"] != "structure" or s.get("exception"):
            continue
        for mname in sorted(s.get("members", {})):
            rows.append((sname, mname) + names_of(sname, mname, new_shapes, old_shapes))
    out.append("/// Sorted by (shape, member).")
    out.append("inline constexpr std::array<member_names, %d> k_members{{" % len(rows))
    for sname, mname, name, item, key, value, flat in rows:
        out.append(
            "    {%s, %s, %s, %s, %s, %s, %s},"
            % (q(sname), q(mname), q(name), q(item), q(key), q(value), "true" if flat else "false")
        )
    out.append("}};")
    out.append("")

    errs = []
    for sname in sorted(new_shapes):
        if not new_shapes[sname].get("exception"):
            continue
        err = old_shapes.get(sname, {}).get("error") or {}
        code = err.get("code", sname)
        status = err.get("httpStatusCode", 400)
        sender = err.get("senderFault", not new_shapes[sname].get("fault", False))
        code, status, sender = QUERY_ERROR_OVERRIDES.get(sname, (code, status, sender))
        errs.append((sname, code, status, sender))
    out.append("/// Every exception shape's query error, sorted by shape.")
    out.append("inline constexpr std::array<query_error, %d> k_errors{{" % len(errs))
    for sname, code, status, sender in errs:
        out.append(
            "    {%s, %s, %d, %s}," % (q(sname), q(code), status, "true" if sender else "false")
        )
    out.append("}};")
    out.append("")
    out.append(FOOTER)
    return "\n".join(out)


def main(argv):
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("json_model")
    ap.add_argument("query_model")
    ap.add_argument("out")
    ap.add_argument("--check", action="store_true", help="fail if OUT is stale")
    args = ap.parse_args(argv)
    load = lambda p: json.loads(pathlib.Path(p).read_text(encoding="utf-8"))  # noqa: E731
    text = generate(load(args.json_model), load(args.query_model))
    out = pathlib.Path(args.out)
    if args.check:
        if not out.exists() or out.read_text(encoding="utf-8") != text:
            print("%s is stale; run %s" % (out, sys.argv[0]), file=sys.stderr)
            return 1
        return 0
    out.write_text(text, encoding="utf-8")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
