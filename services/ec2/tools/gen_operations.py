"""Generate the EC2 operation table from the pinned botocore model.

Reads services/ec2/model/service-2.json and writes
services/ec2/include/kythira/ec2/model/operations.hpp: one entry per
operation, sorted by name, with the request members the front end treats
the same way for every operation (.kiro/specs/ec2-compatible-api/
Requirements 2.1, 3.4, 4.3 and 4.5):

- `ClientToken`: the operation is idempotent by token (Requirement 4.3);
- `DryRun`: the operation answers `DryRunOperation` or
  `UnauthorizedOperation` without changing anything (Requirement 3.4);
- `Filters` (wire name `Filter.N`): a Describe filter list (Requirement 4.5);
- `NextToken` and `MaxResults`: the operation pages (Requirement 4.5).

The EC2 model carries no error shapes: EC2 answers every error with a code
in `<Response><Errors><Error><Code>`, documented outside the model, so the
table has no error column (the SNS and SQS tables do). The header is checked
in so that a model upgrade shows its effect in the pull request's diff.

    gen_operations.py MODEL HEADER          write HEADER
    gen_operations.py MODEL HEADER --check  exit 1 if HEADER is stale

The ctest ec2_operations_up_to_date runs the --check form.
"""

import argparse
import json
import pathlib
import sys

BOTOCORE_VERSION = "1.43.126"

# Request members with one meaning in every operation that has them, and the
# operation_info flag each sets. The member names are the model's; the wire
# name of `Filters` is `Filter` (its locationName), which the codec handles.
FLAGS = (
    ("ClientToken", "_client_token"),
    ("DryRun", "_dry_run"),
    ("Filters", "_filters"),
    ("NextToken", "_paged"),
)


def render(model: dict) -> str:
    meta = model["metadata"]
    if meta.get("protocol") != "ec2":
        raise SystemExit(f"expected the ec2 protocol, the model says {meta.get('protocol')}")
    shapes = model["shapes"]
    if any(shape.get("exception") for shape in shapes.values()):
        raise SystemExit("the EC2 model now has error shapes: give the table an error column")
    ops = sorted(model["operations"].items())
    lines = [
        "// Copyright (c) 2026 Clark Rawlins",
        "// SPDX-License-Identifier: Apache-2.0",
        "",
        "// Generated by services/ec2/tools/gen_operations.py from",
        f"// services/ec2/model/service-2.json (botocore {BOTOCORE_VERSION}). Do not edit:",
        "// change the model or the generator and rerun it.",
        "#pragma once",
        "",
        "#include <array>",
        "#include <string_view>",
        "",
        "namespace kythira::ec2::model {",
        "",
        f'inline constexpr std::string_view botocore_version = "{BOTOCORE_VERSION}";',
        "/// The query protocol's `Version` parameter.",
        f'inline constexpr std::string_view api_version = "{meta["apiVersion"]}";',
        "/// The namespace of every XML response, without the trailing slash the",
        "/// service adds on the wire (design \"EC2 query protocol\").",
        f'inline constexpr std::string_view xml_namespace = "{meta["xmlNamespace"]}";',
        "/// The SigV4 signing name.",
        f'inline constexpr std::string_view signing_name = "{meta.get("signingName", meta["endpointPrefix"])}";',
        "",
        "/// One operation of the pinned EC2 model and the request members the",
        "/// front end handles alike in every operation that has them.",
        "struct operation_info {",
        "    std::string_view _name;",
        "    /// Takes `ClientToken` (Requirement 4.3).",
        "    bool _client_token = false;",
        "    /// Takes `DryRun` (Requirement 3.4).",
        "    bool _dry_run = false;",
        "    /// Takes a `Filter.N` list (Requirement 4.5).",
        "    bool _filters = false;",
        "    /// Takes `NextToken` and pages its answer (Requirement 4.5).",
        "    bool _paged = false;",
        "};",
        "",
        "/// Every operation in the model, sorted by name.",
        f"inline constexpr std::array<operation_info, {len(ops)}> operations{{{{",
    ]
    for name, op in ops:
        members = shapes[op["input"]["shape"]].get("members", {}) if "input" in op else {}
        flags = ", ".join("true" if m in members else "false" for m, _ in FLAGS)
        lines.append(f'    {{"{name}", {flags}}},')
    lines += ["}};", "", "}  // namespace kythira::ec2::model", ""]
    return "\n".join(lines)


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("model", type=pathlib.Path)
    ap.add_argument("header", type=pathlib.Path)
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    text = render(json.loads(args.model.read_text(encoding="utf-8")))
    if args.check:
        current = args.header.read_text(encoding="utf-8") if args.header.exists() else ""
        if current != text:
            print(f"{args.header} is stale: rerun {sys.argv[0]} {args.model} {args.header}",
                  file=sys.stderr)
            return 1
        return 0
    if not args.header.exists() or args.header.read_text(encoding="utf-8") != text:
        args.header.write_text(text, encoding="utf-8")
    return 0


if __name__ == "__main__":
    sys.exit(main())
