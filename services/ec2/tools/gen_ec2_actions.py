"""Generate <kythira/ec2/ec2_actions.hpp> from AWS's service reference.

The input is the `ec2` entry of AWS's machine-readable Service
Authorization Reference
(https://servicereference.us-east-1.amazonaws.com/v1/ec2/ec2.json),
pinned as tools/ec2-service-reference.json. The output holds, for
.kiro/specs/ec2-compatible-api/ Requirement 3.3:

- k_resource_types: every EC2 resource type the reference names, with its
  ARN format (`instance` is
  `arn:${Partition}:ec2:${Region}:${Account}:instance/${InstanceId}`);
- k_condition_keys: every condition key the reference defines;
- k_actions: every `ec2` action with the resource types it acts on, its
  condition keys (the action's own, each resource type's, and the ones the
  action adds per resource, as the reference lists them) and the
  reference's access-level properties. `ec2_actions()` turns these into
  the `aws_action_table` the IAM authorizer registers. The resources and
  keys are indices into the two tables above rather than strings, because
  the EC2 reference spells them out per action: written out like the SNS
  table, this header would be about 300 KB of repeated strings;
- k_operation_actions: per API operation, the `ec2` actions AWS checks for
  it (RunInstances is ec2:RunInstances and, with TagSpecifications,
  ec2:CreateTags), whether it also needs iam:PassRole (an instance
  profile: RunInstances, AssociateIamInstanceProfile and six others), and
  whether any of its actions writes. The few operations the reference
  gives no actions (EC2-Classic retirements) map to their same-named action
  where it defines one;
- ec2_static_roles(): the static-key roles. read-only is every action the
  reference marks neither write nor permissions management (the
  describes, gets, lists and searches); read-write adds running and
  managing instances and their volumes, snapshots and tags (DATA_PLANE
  below); admin is everything, networks, images, key pairs, account
  attributes and permissions included.

The reference is newer than the pinned botocore model and names a few
operations the model does not have yet; they are kept, since a lookup by
an operation the model lacks never happens.

Usage:
    gen_ec2_actions.py REFERENCE OUT [--check]
"""

import argparse
import json
import pathlib
import sys

HEADER = """\
// Copyright (c) 2026 Clark Rawlins
// SPDX-License-Identifier: Apache-2.0

// GENERATED by services/ec2/tools/gen_ec2_actions.py from
// services/ec2/tools/ec2-service-reference.json (AWS Service
// Authorization Reference, {version}). Do not edit; regenerate.

#pragma once

/// @file ec2_actions.hpp
/// @brief The `ec2` action table, resource types, condition keys, the
///        operation-to-action map and the static-key roles
///        (`.kiro/specs/ec2-compatible-api/` Requirement 3.3).

#include <raft/aws_request_authorizer.hpp>
#include <raft/static_key_authorizer.hpp>

#include <algorithm>
#include <array>
#include <cstddef>
#include <cstdint>
#include <optional>
#include <string>
#include <string_view>

namespace kythira::ec2 {{

/// An EC2 resource type and the ARN format of its resources.
struct resource_type {{
    std::string_view _name;
    std::string_view _arn;
}};

/// An `ec2` action. `_resources_at`/`_resources_n` select its resource
/// types in `k_action_resources`, `_keys_at`/`_keys_n` its condition keys
/// in `k_action_keys`; both hold indices into `k_resource_types` and
/// `k_condition_keys`.
struct action_info {{
    std::string_view _name;
    std::uint16_t _resources_at = 0;
    std::uint8_t _resources_n = 0;
    std::uint16_t _keys_at = 0;
    std::uint8_t _keys_n = 0;
    bool _write = false;
    bool _list = false;
    bool _permissions = false;
    bool _tagging_only = false;
}};

/// The `ec2` actions AWS checks for an API operation (unused slots empty),
/// whether it also checks iam:PassRole, and whether any action writes.
struct operation_actions {{
    std::string_view _operation;
    std::array<std::string_view, {width}> _actions;
    bool _pass_role = false;
    bool _writes = false;
}};

// clang-format off
"""

FOOTER = """\
// clang-format on

namespace actions_detail {

template<class Table>
[[nodiscard]] constexpr auto find_by_name(const Table& t, std::string_view name) {
    const auto* it = std::lower_bound(
        t.begin(), t.end(), name, [](const auto& e, std::string_view n) { return e._name < n; });
    return it != t.end() && it->_name == name ? &*it : nullptr;
}

}  // namespace actions_detail

/// The action named `name` (without `ec2:`), or nullptr.
[[nodiscard]] constexpr auto find_action(std::string_view name) -> const action_info* {
    return actions_detail::find_by_name(k_actions, name);
}

/// The resource type named `name` (`instance`, `volume`), or nullptr.
[[nodiscard]] constexpr auto find_resource_type(std::string_view name) -> const resource_type* {
    return actions_detail::find_by_name(k_resource_types, name);
}

/// The entry for an API operation, or nullptr when the reference has none.
[[nodiscard]] constexpr auto find_operation_actions(std::string_view operation)
    -> const operation_actions* {
    const auto* it = std::lower_bound(
        k_operation_actions.begin(), k_operation_actions.end(), operation,
        [](const operation_actions& e, std::string_view name) { return e._operation < name; });
    return it != k_operation_actions.end() && it->_operation == operation ? it : nullptr;
}

/// Whether `action` may act on resources of type `type`.
[[nodiscard]] constexpr auto acts_on(const action_info& action, std::string_view type) -> bool {
    for (std::size_t i = 0; i < action._resources_n; ++i) {
        if (k_resource_types.at(k_action_resources.at(action._resources_at + i))._name == type) {
            return true;
        }
    }
    return false;
}

/// Whether `action` supplies the condition key `key` (as the reference
/// spells it: `ec2:ResourceTag/${TagKey}`).
[[nodiscard]] constexpr auto has_condition_key(const action_info& action, std::string_view key)
    -> bool {
    for (std::size_t i = 0; i < action._keys_n; ++i) {
        if (k_condition_keys.at(k_action_keys.at(action._keys_at + i)) == key) {
            return true;
        }
    }
    return false;
}

/// The ARN of the resource `id` of type `type`: the type's format with
/// `${Partition}`, `${Region}` and `${Account}` filled in and its one other
/// placeholder replaced by `id`. Images and snapshots have no account in
/// their ARNs, as on AWS. nullopt for an unknown type.
[[nodiscard]] inline auto resource_arn(std::string_view type, std::string_view partition,
                                       std::string_view region, std::string_view account,
                                       std::string_view id) -> std::optional<std::string> {
    const auto* t = find_resource_type(type);
    if (t == nullptr) {
        return std::nullopt;
    }
    std::string out;
    std::string_view f = t->_arn;
    while (!f.empty()) {
        const auto open = f.find("${");
        if (open == std::string_view::npos) {
            out += f;
            break;
        }
        out += f.substr(0, open);
        const auto close = f.find('}', open);
        const auto var = f.substr(open + 2, close - open - 2);
        if (var == "Partition") {
            out += partition;
        } else if (var == "Region") {
            out += region;
        } else if (var == "Account") {
            out += account;
        } else {
            out += id;
        }
        f.remove_prefix(close + 1);
    }
    return out;
}

/// Every `ec2` action, its resource ARN formats and condition keys, for
/// the IAM authorizer's service registry.
[[nodiscard]] inline auto ec2_actions() -> aws_auth::aws_action_table {
    aws_auth::aws_action_table t;
    t.service_prefix = "ec2";
    t.actions.reserve(k_actions.size());
    for (const auto& a : k_actions) {
        aws_auth::action_entry e;
        e.name = std::string(a._name);
        for (std::size_t i = 0; i < a._resources_n; ++i) {
            e.resource_templates.emplace_back(
                k_resource_types.at(k_action_resources.at(a._resources_at + i))._arn);
        }
        if (e.resource_templates.empty()) {
            e.resource_templates.emplace_back("*");
        }
        for (std::size_t i = 0; i < a._keys_n; ++i) {
            e.condition_keys.emplace_back(k_condition_keys.at(k_action_keys.at(a._keys_at + i)));
        }
        t.actions.push_back(std::move(e));
    }
    return t;
}

}  // namespace kythira::ec2
"""

# The read-write role's additions: running and managing instances, their
# volumes and snapshots, and tags. Networks, images, key pairs, account
# attributes and permissions stay admin's.
DATA_PLANE = {
    "AttachVolume",
    "CreateSnapshot",
    "CreateSnapshots",
    "CreateTags",
    "CreateVolume",
    "DeleteSnapshot",
    "DeleteTags",
    "DeleteVolume",
    "DetachVolume",
    "ModifyVolume",
    "RebootInstances",
    "RunInstances",
    "StartInstances",
    "StopInstances",
    "TerminateInstances",
}


def q(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def props(action):
    return action.get("Annotations", {}).get("Properties", {})


def b(v):
    return "true" if v else "false"


def generate(ref):
    resources = sorted(ref["Resources"], key=lambda r: r["Name"])
    res_index = {r["Name"]: i for i, r in enumerate(resources)}
    keys = sorted(k["Name"] for k in ref["ConditionKeys"])
    actions = sorted(ref["Actions"], key=lambda a: a["Name"])
    by_name = {a["Name"]: a for a in actions}
    res_by_name = {r["Name"]: r for r in resources}

    # Keys an action names but the reference's key list lacks are added, so
    # every index resolves.
    rows, flat_res, flat_keys = [], [], []
    extra = set()
    for a in actions:
        rs = [r["Name"] for r in a.get("Resources", [])]
        ks = list(a.get("ActionConditionKeys", []))
        for r in a.get("Resources", []):
            ks += res_by_name[r["Name"]].get("ConditionKeys", [])
            ks += r.get("ConditionKeys", [])
        ks = sorted(set(ks))
        extra |= set(ks) - set(keys)
        rows.append((a, rs, ks))
    keys = sorted(set(keys) | extra)
    key_index = {k: i for i, k in enumerate(keys)}
    if len(resources) > 256 or len(keys) > 256:
        raise SystemExit("more than 256 resource types or condition keys: widen the index type")

    entries = []
    for a, rs, ks in rows:
        if len(rs) > 255 or len(ks) > 255:
            raise SystemExit("%s: more than 255 resources or keys" % a["Name"])
        entries.append((a, len(flat_res), len(rs), len(flat_keys), len(ks)))
        flat_res += [res_index[r] for r in rs]
        flat_keys += [key_index[k] for k in ks]
    if len(flat_res) > 65535 or len(flat_keys) > 65535:
        raise SystemExit("action index tables exceed 16 bits")

    ops = sorted(ref["Operations"], key=lambda o: o["Name"])
    op_rows = []
    for o in ops:
        acts = sorted(
            a["Name"] for a in o.get("AuthorizedActions", []) if a.get("Service", "ec2") == "ec2"
        )
        if not o.get("AuthorizedActions") and o["Name"] in by_name:
            # The reference lists no actions for a few retired operations
            # whose same-named action it still defines.
            acts = [o["Name"]]
        pass_role = any(
            a.get("Service") == "iam" and a["Name"] == "PassRole"
            for a in o.get("AuthorizedActions", [])
        )
        writes = any(props(by_name[a]).get("IsWrite", False) for a in acts if a in by_name)
        op_rows.append((o["Name"], acts, pass_role, writes))
    width = max(len(r[1]) for r in op_rows)

    out = [HEADER.format(version=ref.get("Version", "unversioned"), width=width)]

    out.append("/// Every EC2 resource type, sorted by name.")
    out.append(
        "inline constexpr std::array<resource_type, %d> k_resource_types{{" % len(resources)
    )
    for r in resources:
        if len(r["ARNFormats"]) != 1:
            raise SystemExit("%s: expected one ARN format" % r["Name"])
        out.append("    {%s, %s}," % (q(r["Name"]), q(r["ARNFormats"][0])))
    out.append("}};")
    out.append("")

    out.append("/// Every condition key, sorted.")
    out.append("inline constexpr std::array<std::string_view, %d> k_condition_keys{{" % len(keys))
    for k in keys:
        out.append("    %s," % q(k))
    out.append("}};")
    out.append("")

    def flat(name, values):
        out.append("inline constexpr std::array<std::uint8_t, %d> %s{{" % (len(values), name))
        for i in range(0, len(values), 24):
            out.append("    " + ", ".join(str(v) for v in values[i : i + 24]) + ",")
        out.append("}};")
        out.append("")

    out.append("/// Resource type indices, per action (`action_info::_resources_at`).")
    flat("k_action_resources", flat_res)
    out.append("/// Condition key indices, per action (`action_info::_keys_at`).")
    flat("k_action_keys", flat_keys)

    out.append("/// Every `ec2` action, sorted by name.")
    out.append("inline constexpr std::array<action_info, %d> k_actions{{" % len(entries))
    for a, ra, rn, ka, kn in entries:
        p = props(a)
        out.append(
            "    {%s, %d, %d, %d, %d, %s, %s, %s, %s},"
            % (
                q(a["Name"]),
                ra,
                rn,
                ka,
                kn,
                b(p.get("IsWrite", False)),
                b(p.get("IsList", False)),
                b(p.get("IsPermissionManagement", False)),
                b(p.get("IsTaggingOnly", False)),
            )
        )
    out.append("}};")
    out.append("")

    out.append("/// Sorted by operation name.")
    out.append(
        "inline constexpr std::array<operation_actions, %d> k_operation_actions{{" % len(op_rows)
    )
    for name, acts, pass_role, writes in op_rows:
        out.append(
            "    {%s, {%s}, %s, %s}," % (q(name), ", ".join(map(q, acts)), b(pass_role), b(writes))
        )
    out.append("}};")
    out.append("")

    missing = DATA_PLANE - set(by_name)
    if missing:
        raise SystemExit("data-plane actions not in the reference: %s" % sorted(missing))
    ro, rw = [], []
    for a in actions:
        p = props(a)
        if not p.get("IsWrite", False) and not p.get("IsPermissionManagement", False):
            ro.append(a["Name"])
        elif a["Name"] in DATA_PLANE:
            rw.append(a["Name"])
    out.append("/// The static-key roles: read-only describes and gets, read-write adds")
    out.append("/// instances, their volumes, snapshots and tags, admin is everything")
    out.append("/// (`static_key_authorizer`).")
    out.append("[[nodiscard]] inline auto ec2_static_roles() -> aws_auth::static_role_table {")
    out.append("    return {")
    out.append('        "ec2",')
    out.append("        {")
    for name in ro:
        out.append("            %s," % q(name))
    out.append("        },")
    out.append("        {%s}," % ", ".join(map(q, rw)))
    out.append("    };")
    out.append("}")
    out.append("")
    out.append(FOOTER)
    return "\n".join(out)


def main(argv):
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("reference")
    ap.add_argument("out")
    ap.add_argument("--check", action="store_true", help="fail if OUT is stale")
    args = ap.parse_args(argv)
    text = generate(json.loads(pathlib.Path(args.reference).read_text(encoding="utf-8")))
    out = pathlib.Path(args.out)
    if args.check:
        if not out.exists() or out.read_text(encoding="utf-8") != text:
            print("%s is stale; run %s" % (out, sys.argv[0]), file=sys.stderr)
            return 1
        return 0
    out.write_text(text, encoding="utf-8")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
