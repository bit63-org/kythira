"""Generate <kythira/sns/sns_actions.hpp> from AWS's service reference.

The input is the `sns` entry of AWS's machine-readable Service
Authorization Reference
(https://servicereference.us-east-1.amazonaws.com/v1/sns/sns.json),
pinned as tools/sns-service-reference.json. The output holds:

- sns_actions(): every action with the ARN formats of the resources it
  acts on (`topic`) and its condition keys (action keys plus the
  resources'), for the IAM authorizer's service registry
  (.kiro/specs/sns-compatible-notifications/ Requirement 3.2);
- k_operation_actions: per API operation, every `sns` action AWS checks
  for it, and whether any of them writes. PublishBatch is authorized as
  sns:Publish, the one operation whose action has another name; CreateTopic
  also lists sns:TagResource and sns:PutDataProtectionPolicy, which it
  needs only when the request has tags or a data protection policy;
- sns_static_roles(): the static-key roles. read-only is every action the
  reference marks neither write nor permissions management (get, list,
  CheckIfPhoneNumberIsOptedOut); read-write adds the data plane listed
  below (publishing and managing one's own subscriptions); admin is
  everything, topic management and permissions included.

Actions of other services (iam:PassRole for Subscribe with a
SubscriptionRoleArn) are left out: they are not ours to authorize.

Usage:
    gen_sns_actions.py REFERENCE OUT [--check]
"""

import argparse
import json
import pathlib
import sys

HEADER = """\
// Copyright (c) 2026 Clark Rawlins
// SPDX-License-Identifier: Apache-2.0

// GENERATED by services/sns/tools/gen_sns_actions.py from
// services/sns/tools/sns-service-reference.json (AWS Service
// Authorization Reference, {version}). Do not edit; regenerate.

#pragma once

/// @file sns_actions.hpp
/// @brief The `sns` action table, the operation-to-action map and the
///        static-key roles (`.kiro/specs/sns-compatible-notifications/`
///        Requirement 3.2).

#include <raft/aws_request_authorizer.hpp>
#include <raft/static_key_authorizer.hpp>

#include <algorithm>
#include <array>
#include <string_view>

namespace kythira::sns {{

// clang-format off
"""

FOOTER = """\
// clang-format on

/// The entry for an API operation, or nullptr when the reference has none.
[[nodiscard]] constexpr auto find_operation_actions(std::string_view operation)
    -> const operation_actions* {
    const auto* it = std::lower_bound(
        k_operation_actions.begin(), k_operation_actions.end(), operation,
        [](const operation_actions& e, std::string_view name) { return e.operation < name; });
    return it != k_operation_actions.end() && it->operation == operation ? it : nullptr;
}

}  // namespace kythira::sns
"""


# The read-write role's additions: publishing, and subscribing,
# confirming and managing subscriptions. Topic management (create, delete,
# attributes, tags) and permissions stay admin's.
DATA_PLANE = {
    "ConfirmSubscription",
    "Publish",
    "SetSubscriptionAttributes",
    "Subscribe",
    "Unsubscribe",
}


def q(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def props(action):
    return action.get("Annotations", {}).get("Properties", {})


def generate(ref):
    resources = {r["Name"]: r for r in ref["Resources"]}
    actions = {a["Name"]: a for a in ref["Actions"]}
    out = [HEADER.format(version=ref.get("Version", "unversioned"))]

    out.append("/// Every `sns` action, its resource ARN formats and condition keys.")
    out.append("[[nodiscard]] inline auto sns_actions() -> aws_auth::aws_action_table {")
    out.append("    return {")
    out.append('        .service_prefix = "sns",')
    out.append("        .actions = {")
    for name in sorted(actions):
        a = actions[name]
        arns, keys = [], list(a.get("ActionConditionKeys", []))
        for r in a.get("Resources", []):
            res = resources[r["Name"]]
            arns += res["ARNFormats"]
            keys += res.get("ConditionKeys", [])
            keys += r.get("ConditionKeys", [])
        if not arns:
            arns = ["*"]
        keys = sorted(set(keys))
        out.append(
            "            {%s, {%s}, {%s}},"
            % (q(name), ", ".join(map(q, arns)), ", ".join(map(q, keys)))
        )
    out.append("        },")
    out.append("    };")
    out.append("}")
    out.append("")

    ops = sorted(ref["Operations"], key=lambda o: o["Name"])
    rows = []
    for o in ops:
        acts = sorted(
            a["Name"]
            for a in o.get("AuthorizedActions", [])
            if a.get("Service", "sns") == "sns"
        )
        writes = any(props(actions[a]).get("IsWrite", False) for a in acts if a in actions)
        rows.append((o["Name"], acts, writes))
    width = max(len(r[1]) for r in rows)
    out.append("/// Every `sns` action AWS may check for an API operation (a superset;")
    out.append("/// (see the generator's docstring), and whether any of them writes.")
    out.append("struct operation_actions {")
    out.append("    std::string_view operation;")
    out.append("    std::array<std::string_view, %d> actions;  // unused slots empty" % width)
    out.append("    bool writes = false;")
    out.append("};")
    out.append("")
    out.append("/// Sorted by operation name.")
    out.append(
        "inline constexpr std::array<operation_actions, %d> k_operation_actions{{" % len(rows)
    )
    for name, acts, writes in rows:
        out.append(
            "    {%s, {%s}, %s}," % (q(name), ", ".join(map(q, acts)), "true" if writes else "false")
        )
    out.append("}};")
    out.append("")

    missing = DATA_PLANE - set(actions)
    if missing:
        raise SystemExit("data-plane actions not in the reference: %s" % sorted(missing))
    ro, rw = [], []
    for name in sorted(actions):
        p = props(actions[name])
        write, perm = (p.get(k, False) for k in ("IsWrite", "IsPermissionManagement"))
        if not write and not perm:
            ro.append(name)
        elif name in DATA_PLANE:
            rw.append(name)
    out.append("/// The static-key roles: read-only gets and lists, read-write adds")
    out.append("/// publishing and subscriptions, admin is everything")
    out.append("/// (`static_key_authorizer`).")
    out.append("[[nodiscard]] inline auto sns_static_roles() -> aws_auth::static_role_table {")
    out.append("    return {")
    out.append('        "sns",')
    out.append("        {%s}," % ", ".join(map(q, ro)))
    out.append("        {%s}," % ", ".join(map(q, rw)))
    out.append("    };")
    out.append("}")
    out.append("")
    out.append(FOOTER)
    return "\n".join(out)


def main(argv):
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("reference")
    ap.add_argument("out")
    ap.add_argument("--check", action="store_true", help="fail if OUT is stale")
    args = ap.parse_args(argv)
    text = generate(json.loads(pathlib.Path(args.reference).read_text(encoding="utf-8")))
    out = pathlib.Path(args.out)
    if args.check:
        if not out.exists() or out.read_text(encoding="utf-8") != text:
            print("%s is stale; run %s" % (out, sys.argv[0]), file=sys.stderr)
            return 1
        return 0
    out.write_text(text, encoding="utf-8")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
