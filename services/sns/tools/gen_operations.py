"""Generate the SNS operation table from the pinned botocore model.

Reads services/sns/model/service-2.json and writes
services/sns/include/kythira/sns/sns_operations.hpp: one entry per
operation, sorted by name, with whether it is the batch form of another
operation and which of the model's error shapes it may return, plus the
model's error shapes themselves with the query-protocol code and HTTP status
each is answered with. The header is checked in so that a model upgrade shows
its effect in the pull request's diff
(.kiro/specs/sns-compatible-notifications/ Requirement 2.1).

    gen_operations.py MODEL HEADER          write HEADER
    gen_operations.py MODEL HEADER --check  exit 1 if HEADER is stale

The ctest sns_operations_up_to_date runs the --check form.
"""

import argparse
import json
import pathlib
import sys

BOTOCORE_VERSION = "1.43.126"


def error_info(name: str, shape: dict) -> tuple[str, int, bool]:
    """The query error code, HTTP status and sender fault of an error shape.

    SNS's model carries an `error` block on almost every shape. One without
    it is answered like any unmodelled exception: its shape name as the code,
    HTTP 400, a sender fault.
    """
    err = shape.get("error", {})
    return err.get("code", name), int(err.get("httpStatusCode", 400)), bool(
        err.get("senderFault", "httpStatusCode" not in err or err["httpStatusCode"] < 500))


def render(model: dict) -> str:
    meta = model["metadata"]
    if meta.get("protocol") != "query":
        raise SystemExit(f"expected the query protocol, the model says {meta.get('protocol')}")
    shapes = model["shapes"]
    ops = sorted(model["operations"].items())
    errors = sorted(name for name, shape in shapes.items() if shape.get("exception"))
    if len(errors) > 64:
        raise SystemExit(f"{len(errors)} error shapes do not fit a 64-bit mask")
    index = {name: i for i, name in enumerate(errors)}
    for name, op in ops:
        for e in op.get("errors", []):
            if e["shape"] not in index:
                raise SystemExit(f"{name} lists error {e['shape']}, which is not an exception shape")
    names = {name for name, _ in ops}
    lines = [
        "// Generated by services/sns/tools/gen_operations.py from",
        f"// services/sns/model/service-2.json (botocore {BOTOCORE_VERSION}). Do not edit:",
        "// change the model or the generator and rerun it.",
        "#pragma once",
        "",
        "#include <array>",
        "#include <cstddef>",
        "#include <cstdint>",
        "#include <string_view>",
        "",
        "namespace kythira::sns {",
        "",
        f'inline constexpr std::string_view botocore_version = "{BOTOCORE_VERSION}";',
        "/// The query protocol's `Version` parameter.",
        f'inline constexpr std::string_view api_version = "{meta["apiVersion"]}";',
        "/// The namespace of every XML response (Requirement 3.1).",
        f'inline constexpr std::string_view xml_namespace = "{meta["xmlNamespace"]}";',
        "/// The SigV4 signing name.",
        f'inline constexpr std::string_view signing_name = "{meta.get("signingName", meta["endpointPrefix"])}";',
        "",
        "/// One error shape of the model, as the query protocol answers it.",
        "struct error_info {",
        "    /// The shape name in the model (`NotFoundException`).",
        "    std::string_view _shape;",
        "    /// `<Code>` in the XML error response (`NotFound`).",
        "    std::string_view _code;",
        "    std::uint16_t _http_status = 400;",
        "    /// `<Type>Sender</Type>` rather than `Receiver`.",
        "    bool _sender_fault = true;",
        "};",
        "",
        "/// Every error shape in the model, sorted by shape name. An operation",
        "/// names the ones it may return by index into this array.",
        f"inline constexpr std::array<error_info, {len(errors)}> error_shapes{{{{",
    ]
    for e in errors:
        code, status, sender = error_info(e, shapes[e])
        lines.append(f'    {{"{e}", "{code}", {status}, {"true" if sender else "false"}}},')
    lines += [
        "}};",
        "",
        "/// One operation of the pinned SNS model.",
        "struct operation_info {",
        "    std::string_view _name;",
        "    /// The batch form of another operation (`PublishBatch` of",
        "    /// `Publish`): up to ten entries, a result or error per entry.",
        "    bool _batch = false;",
        "    /// Bit i set: the operation may return `error_shapes[i]`.",
        "    std::uint64_t _errors = 0;",
        "",
        "    [[nodiscard]] constexpr auto may_return(std::size_t error_index) const -> bool {",
        "        return error_index < 64 && ((_errors >> error_index) & 1U) != 0;",
        "    }",
        "};",
        "",
        "/// Every operation in the model, sorted by name.",
        f"inline constexpr std::array<operation_info, {len(ops)}> operations{{{{",
    ]
    for name, op in ops:
        batch = name.endswith("Batch") and name[: -len("Batch")] in names
        mask = 0
        for e in op.get("errors", []):
            mask |= 1 << index[e["shape"]]
        lines.append(f'    {{"{name}", {"true" if batch else "false"}, 0x{mask:x}U}},')
    lines += ["}};", "", "}  // namespace kythira::sns", ""]
    return "\n".join(lines)


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("model", type=pathlib.Path)
    ap.add_argument("header", type=pathlib.Path)
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    text = render(json.loads(args.model.read_text(encoding="utf-8")))
    if args.check:
        current = args.header.read_text(encoding="utf-8") if args.header.exists() else ""
        if current != text:
            print(f"{args.header} is stale: rerun {sys.argv[0]} {args.model} {args.header}",
                  file=sys.stderr)
            return 1
        return 0
    if not args.header.exists() or args.header.read_text(encoding="utf-8") != text:
        args.header.write_text(text, encoding="utf-8")
    return 0


if __name__ == "__main__":
    sys.exit(main())
