/// Whether `upper` (upper case) is a command or `CONTAINER|SUB` subcommand
/// name that Redis 7.2 or Valkey 8 knows.
[[nodiscard]] constexpr auto is_known_redis_command(std::string_view upper) -> bool {
    return std::binary_search(std::begin(k_redis_known_commands), std::end(k_redis_known_commands),
                              upper);
}

static_assert(std::ranges::is_sorted(k_redis_known_commands));

