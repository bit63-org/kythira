"""Generate the S3 operation table from the pinned botocore model.

Reads services/s3/model/s3-2006-03-01.json and writes
services/s3/include/kythira/s3/model/operations.hpp: one entry per
operation, sorted by name, with what the REST-XML codec (task 3) routes and
frames by: the HTTP method, the request URI template with its literal query
keys, the required query parameters and headers, the success status, whether the request or response body is a
streaming payload, and whether the request needs a checksum. The header is
checked in so that a model upgrade shows its effect in the pull request's
diff (.kiro/specs/s3-compatible-storage/ Requirement 2.3).

    gen_operations.py MODEL HEADER          write HEADER
    gen_operations.py MODEL HEADER --check  exit 1 if HEADER is stale

The ctest s3_operations_up_to_date runs the --check form.
"""

import argparse
import json
import pathlib
import sys

BOTOCORE_VERSION = "1.43.126"
MODEL_LABEL = "services/s3/model/s3-2006-03-01.json"


def streaming_payload(model: dict, shape_name: str | None) -> bool:
    """True when the shape's payload member is a streaming blob (the object
    body of PutObject, UploadPart, GetObject, ...)."""
    if not shape_name:
        return False
    shapes = model["shapes"]
    shape = shapes[shape_name]
    payload = shape.get("payload")
    if not payload:
        return False
    member = shape["members"][payload]
    target = shapes[member["shape"]]
    # The S3 model marks streaming on the member; other models mark the shape.
    streaming = member.get("streaming") or target.get("streaming")
    return bool(streaming) and target.get("type") == "blob"


def event_stream_output(model: dict, shape_name: str | None) -> bool:
    """True when the response payload is an event stream (SelectObjectContent)."""
    if not shape_name:
        return False
    shapes = model["shapes"]
    for member in shapes[shape_name].get("members", {}).values():
        if shapes.get(member.get("shape"), {}).get("eventstream"):
            return True
    return False


def checksum_required(op: dict) -> bool:
    """The request must carry Content-MD5 or an x-amz-checksum-* header."""
    if op.get("httpChecksumRequired"):
        return True
    return bool(op.get("httpChecksum", {}).get("requestChecksumRequired"))


def required_members(model: dict, shape_name: str | None, location: str) -> str:
    """The wire names of the input's required members bound to `location`
    (querystring or header), sorted and comma-separated. The router needs
    them where operations share a method and path: UploadPart is PutObject
    with `partNumber` and `uploadId`, CopyObject is PutObject with
    `x-amz-copy-source`."""
    if not shape_name:
        return ""
    shape = model["shapes"][shape_name]
    names = []
    for member_name in shape.get("required", []):
        member = shape["members"][member_name]
        if member.get("location") == location:
            names.append(member.get("locationName", member_name))
    return ",".join(sorted(names, key=str.lower))


def cxx_bool(value: bool) -> str:
    return "true" if value else "false"


def render(model: dict) -> str:
    meta = model["metadata"]
    ops = sorted(model["operations"].items())
    lines = [
        "// Generated by services/s3/tools/gen_operations.py from",
        f"// {MODEL_LABEL} (botocore {BOTOCORE_VERSION}). Do not edit:",
        "// change the model or the generator and rerun it.",
        "#pragma once",
        "",
        "#include <array>",
        "#include <cstdint>",
        "#include <string_view>",
        "",
        "namespace kythira::s3::model {",
        "",
        "/// One operation of the pinned S3 model.",
        "struct operation_info {",
        "    std::string_view _name;",
        "    /// GET, HEAD, PUT, POST or DELETE.",
        "    std::string_view _method;",
        "    /// The model's `requestUri`: `{Bucket}` and `{Key+}` are labels,",
        "    /// and what follows `?` are the query keys that tell operations on",
        "    /// one path apart (`?uploads`, `?list-type=2`, `?select&select-type=2`).",
        "    std::string_view _request_uri;",
        "    /// The status of a successful response.",
        "    std::uint16_t _response_code = 200;",
        "    /// The request body is the object's bytes, streamed (PutObject, UploadPart).",
        "    bool _streaming_input = false;",
        "    /// The response body is the object's bytes, streamed (GetObject).",
        "    bool _streaming_output = false;",
        "    /// The response is an event stream (SelectObjectContent).",
        "    bool _event_stream = false;",
        "    /// The request must carry Content-MD5 or an x-amz-checksum-* header.",
        "    bool _checksum_required = false;",
        "    /// Deprecated in the model in favour of a newer operation.",
        "    bool _deprecated = false;",
        "    /// Required query parameters and headers, by wire name, sorted and",
        "    /// comma-separated: what tells apart operations on one method and",
        "    /// path (`partNumber,uploadId` for UploadPart).",
        "    std::string_view _required_query;",
        "    std::string_view _required_headers;",
        "};",
        "",
        f'inline constexpr std::string_view botocore_version = "{BOTOCORE_VERSION}";',
        f'inline constexpr std::string_view api_version = "{meta["apiVersion"]}";',
        f'inline constexpr std::string_view protocol = "{meta["protocol"]}";',
        "",
        "/// Every operation in the model, sorted by name. Fields in declaration",
        "/// order; one line per operation, so a model upgrade's diff is one line",
        "/// per changed operation.",
        "// clang-format off",
        f"inline constexpr std::array<operation_info, {len(ops)}> operations{{{{",
    ]
    for name, op in ops:
        http = op["http"]
        input_shape = op.get("input", {}).get("shape")
        output_shape = op.get("output", {}).get("shape")
        fields = [
            f'"{name}"',
            f'"{http["method"]}"',
            f'"{http["requestUri"]}"',
            str(http.get("responseCode", 200)),
            cxx_bool(streaming_payload(model, input_shape)),
            cxx_bool(streaming_payload(model, output_shape)),
            cxx_bool(event_stream_output(model, output_shape)),
            cxx_bool(checksum_required(op)),
            cxx_bool(bool(op.get("deprecated"))),
            f'"{required_members(model, input_shape, "querystring")}"',
            f'"{required_members(model, input_shape, "header")}"',
        ]
        lines.append(f"    {{{', '.join(fields)}}},")
    lines += ["}};", "// clang-format on", "", "}  // namespace kythira::s3::model", ""]
    return "\n".join(lines)


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("model", type=pathlib.Path)
    ap.add_argument("header", type=pathlib.Path)
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    text = render(json.loads(args.model.read_text(encoding="utf-8")))
    if args.check:
        current = args.header.read_text(encoding="utf-8") if args.header.exists() else ""
        if current != text:
            print(f"{args.header} is stale: rerun {sys.argv[0]} {args.model} {args.header}",
                  file=sys.stderr)
            return 1
        return 0
    if not args.header.exists() or args.header.read_text(encoding="utf-8") != text:
        args.header.write_text(text, encoding="utf-8")
    return 0


if __name__ == "__main__":
    sys.exit(main())
